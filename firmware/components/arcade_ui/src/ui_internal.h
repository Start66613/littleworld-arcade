/* ------------------------------------------------------- game module hooks */
typedef struct arcade_game_host {
    void (*set_score)(uint32_t score);
    void (*set_extra)(const char *text);
    void (*game_over)(uint32_t score, int won);
} arcade_game_host_t;

typedef struct arcade_game_module {
    arcade_game_id_t id;
    const char *title;    /* shown in the game header */
    const char *subtitle; /* one line shown on the menu card */
    const char *hint;     /* control hint shown under the play field */
    uint32_t accent;      /* accent colour of the card */
    uint32_t soft;        /* pale tint used behind the menu preview */
    /** Build the game inside @p playfield. @p host stays valid until destroy. */
    void (*create)(lv_obj_t *playfield, const arcade_game_host_t *host);
    /** Delete timers and free game state. LVGL objects are deleted by the host. */
    void (*destroy)(void);
    /** 1 = stop simulation, 0 = resume. */
    void (*set_paused)(int paused);
    /** Optional: extra controls placed in the game header. */
    void (*build_controls)(lv_obj_t *bar);
} arcade_game_module_t;

extern const arcade_game_module_t arcade_game_2048;
extern const arcade_game_module_t arcade_game_snake;
extern const arcade_game_module_t arcade_game_breakout;

